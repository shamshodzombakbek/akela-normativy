def t(lang: str, key: str) -> str:
    lang = lang if lang in _T else "ru"
    return _T[lang].get(key) or _T["ru"].get(key) or key


def month_name(lang: str, month: int) -> str:
    lang = lang if lang in _MONTHS else "ru"
    if 1 <= month <= 12:
        return _MONTHS[lang][month]
    return str(month)


def weekday_labels(lang: str) -> list[str]:
    lang = lang if lang in _WD else "ru"
    return list(_WD[lang])
